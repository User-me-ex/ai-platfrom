// 1. Locate API Key
function getApiKey() {
  if (process.env.GEMINI_API_KEY) return process.env.GEMINI_API_KEY;

  // Try reading from VS Code extension storage
  const extConfigPath = path.join(os.homedir(), 'AppData', 'Roaming', 'Code', 'User', 'globalStorage');
  // Check workspace settings or prompt
  const localSettings = path.join(process.cwd(), '.vscode', 'settings.json');
  if (fs.existsSync(localSettings)) {
    try {
      const cfg = JSON.parse(fs.readFileSync(localSettings, 'utf8'));
      if (cfg['antigravity.voice.apiKey']) return cfg['antigravity.voice.apiKey'];
    } catch {}
  }
  return null;
}

