// 3. Create standard 44-byte WAV header
function createWavHeader(dataLength, sampleRate = 24000, channels = 1, bits = 16) {
  const header = Buffer.alloc(44);
  header.write('RIFF', 0);
  header.writeUInt32LE(36 + dataLength, 4);
  header.write('WAVE', 8);
  header.write('fmt ', 12);
  header.writeUInt32LE(16, 16);
  header.writeUInt16LE(1, 20); // PCM
  header.writeUInt16LE(channels, 22);
  header.writeUInt32LE(sampleRate, 24);
  header.writeUInt32LE(sampleRate * channels * (bits / 8), 28);
  header.writeUInt16LE(channels * (bits / 8), 32);
  header.writeUInt16LE(bits, 34);
  header.write('data', 36);
  header.writeUInt32LE(dataLength, 40);
  return header;
}

async function main() {
  const args = process.argv.slice(2);
  let voiceName = 'Kore';
  let text = '';

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--voice' && args[i + 1]) {
      voiceName = args[++i];
    } else {
      text += (text ? ' ' : '') + args[i];
    }
  }

  if (!text) {
    text = 'Hello! This audio was generated by 9 Router Voice AI and is ready to use on any platform.';
  }

  console.log('====================================================');
  console.log('       9 ROUTER AUDIO EXPORTER FOR OTHER PLATFORMS   ');
  console.log('====================================================');
  console.log('Text to synthesize:', text);
  console.log('Voice:', voiceName);

  // Check recordings folder
  const recDir = path.join(process.cwd(), '.antigravity', 'recordings');
  fs.mkdirSync(recDir, { recursive: true });

  // List existing recordings
  const existingFiles = fs.readdirSync(recDir)
    .filter(f => f.endsWith('.mp3') || f.endsWith('.wav'))
    .map(f => ({ name: f, path: path.join(recDir, f), mtime: fs.statSync(path.join(recDir, f)).mtime }))
    .sort((a, b) => b.mtime - a.mtime);

  console.log(`\nFound ${existingFiles.length} saved recording(s) in: ${recDir}`);
  if (existingFiles.length > 0) {
    console.log('Latest 3 recordings available right now:');
    existingFiles.slice(0, 3).forEach((f, idx) => {
      console.log(`  [${idx + 1}] ${f.name} (${f.mtime.toLocaleTimeString()}) -> ${f.path}`);
    });
  }

  console.log('\n[Tip] How to copy and use audio on other platforms:');
  console.log('  1. WhatsApp / Telegram: Drag and drop the .mp3 file into any chat.');
  console.log('  2. YouTube / Premiere Pro / CapCut: Import the lossless 24 kHz .wav file into your timeline.');
  console.log('  3. In VS Code: Click "📂 Recordings" in the 9 Router Voice tab to open the folder in Windows File Explorer.');
  console.log('====================================================\n');
}

main().catch(console.error);
